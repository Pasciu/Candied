using System.Globalization;
using System.Text;
using Candied.Core.Models;

namespace Candied.Workspace.Rendering;

/// <summary>
/// Pure template renderer that formats a GameArchitectureOverview into a rich,
/// GitHub-flavored Markdown guide for developers and AI agents.
/// </summary>
internal static class GameOverviewTemplateRenderer
{
    public static string Render(GameArchitectureOverview overview)
    {
        var sb = new StringBuilder();

        sb.AppendLine(CultureInfo.InvariantCulture, $"# {overview.GameName} - Architecture & Modding Guide");
        sb.AppendLine();
        sb.AppendLine("> Automated reverse-engineering summary generated by Candied Workbench.");
        sb.AppendLine();

        // 1. Runtime & Engine Info
        sb.AppendLine("## 1. Engine & Runtime Environment");
        sb.AppendLine();
        sb.AppendLine("| Property | Value |");
        sb.AppendLine("|---|---|");
        sb.AppendLine(CultureInfo.InvariantCulture, $"| **Engine Type** | Unity ({overview.RuntimeKind}) |");
        sb.AppendLine(CultureInfo.InvariantCulture, $"| **Unity Version** | {overview.UnityVersion} |");
        sb.AppendLine(CultureInfo.InvariantCulture, $"| **Target Framework** | `{overview.TargetFramework}` |");
        sb.AppendLine(CultureInfo.InvariantCulture, $"| **Indexed Types** | {overview.TotalTypesIndexed:N0} |");
        sb.AppendLine(CultureInfo.InvariantCulture, $"| **Indexed Methods** | {overview.TotalMethodsIndexed:N0} |");
        sb.AppendLine();

        // 2. Identified Assemblies
        sb.AppendLine("## 2. Identified Game Assemblies");
        sb.AppendLine();
        sb.AppendLine("The following assemblies contain game logic or core game systems prioritized for modding:");
        sb.AppendLine();
        sb.AppendLine("| Assembly | Size (KB) | Role |");
        sb.AppendLine("|---|---|---|");

        foreach (var asm in overview.Assemblies)
        {
            var sizeKb = asm.SizeBytes / 1024.0;
            var role = asm.IsGameLogic ? "**Core Game Logic**" : "Game Framework";
            sb.AppendLine(CultureInfo.InvariantCulture, $"| `{asm.AssemblyName}` | {sizeKb:N1} KB | {role} |");
        }
        sb.AppendLine();

        // 3. Key Gameplay Systems & Managers
        sb.AppendLine("## 3. Key Gameplay Systems & Managers");
        sb.AppendLine();
        if (overview.KeyManagers.Count == 0)
        {
            sb.AppendLine("*No prominent Manager or Controller classes detected in indexed assemblies.*");
        }
        else
        {
            sb.AppendLine("These high-level manager and controller classes serve as prime targets for Harmony hooks:");
            sb.AppendLine();
            foreach (var mgr in overview.KeyManagers)
            {
                sb.AppendLine(CultureInfo.InvariantCulture, $"- **`{mgr}`**");
            }
        }
        sb.AppendLine();

        // 4. Modding Guidelines & Patterns
        sb.AppendLine("## 4. Recommended Modding Patterns");
        sb.AppendLine();
        sb.AppendLine("1. **Publicized Access:** Game assemblies are publicized via `BepInEx.AssemblyPublicizer.MSBuild`. Access private and internal fields directly without reflection.");
        sb.AppendLine("2. **Harmony Patching:** Hook into `Awake`, `Start`, or state transition methods. Always prefer Prefix/Postfix with publicized members over fragile transpilers when possible.");
        sb.AppendLine("3. **Runtime Diagnostics:** Monitor BepInEx logs in real-time using Candied `logs` to diagnose exceptions immediately without restarting.");
        sb.AppendLine();

        // 5. Navigation
        sb.AppendLine("## 5. Knowledge Hub Navigation");
        sb.AppendLine();
        sb.AppendLine("- [Namespace & Class Cheat-Sheet](./NAMESPACES.md): Explore classes and interfaces grouped by namespace.");
        sb.AppendLine("- [Hierarchical Symbol Map](./SYMBOLS_INDEX.json): Lightweight JSON symbol directory for instant lookup.");

        return sb.ToString();
    }
}
